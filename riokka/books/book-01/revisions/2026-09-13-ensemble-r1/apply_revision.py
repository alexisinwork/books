def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def set_paragraph_text(paragraph, text: str) -> None:
    if not paragraph.runs:
        paragraph.add_run(text)
        return
    paragraph.runs[0].text = text
    for run in paragraph.runs[1:]:
        run.text = ""


def insert_clone_after(paragraph, text: str):
    xml = copy.deepcopy(paragraph._p)
    paragraph._p.addnext(xml)
    clone = paragraph.__class__(xml, paragraph._parent)
    set_paragraph_text(clone, text)
    return clone


def apply_block(doc, block: dict) -> dict:
    hits = [
        (index, paragraph)
        for index, paragraph in enumerate(doc.paragraphs)
        if paragraph.text.rstrip("\r\n") == block["before"]
    ]
    if len(hits) != 1:
        raise ValueError(
            f"{block['id']}: expected one exact paragraph, found {len(hits)}"
        )
    source_index, paragraph = hits[0]
    replacements = block["after"]
    set_paragraph_text(paragraph, replacements[0])
    current = paragraph
    for text in replacements[1:]:
        current = insert_clone_after(current, text)
    return {
        "id": block["id"],
        "chapter": block["chapter"],
        "reason": block["reason"],
        "source_paragraph_index_zero_based": source_index,
        "source_paragraph_label": f"p{source_index + 1}",
        "before": block["before"],
        "after": replacements,
    }


def apply_inline(doc, replacement: dict) -> dict:
    hits = [
        (index, paragraph)
        for index, paragraph in enumerate(doc.paragraphs)
        if replacement["before"] in paragraph.text
    ]
    if len(hits) != 1:
        raise ValueError(
            f"{replacement['id']}: expected one inline occurrence, found {len(hits)}"
        )
    source_index, paragraph = hits[0]
    if replacement["after"] in paragraph.text:
        raise ValueError(f"{replacement['id']}: replacement already present")
    updated = paragraph.text.replace(replacement["before"], replacement["after"])
    set_paragraph_text(paragraph, updated)
    return {
        "id": replacement["id"],
        "chapter": replacement["chapter"],
        "reason": replacement["reason"],
        "source_paragraph_index_zero_based": source_index,
        "source_paragraph_label": f"p{source_index + 1}",
        "before": replacement["before"],
        "after": [replacement["after"]],
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--log", type=Path, required=True)
    args = parser.parse_args()

    actual = sha256(args.source)
    if actual != SOURCE_SHA256:
        raise ValueError(f"source hash mismatch: expected {SOURCE_SHA256}, got {actual}")

    doc = Document(args.source)
    changes = [apply_block(doc, block) for block in BLOCKS]
    changes.extend(apply_inline(doc, replacement) for replacement in INLINE_REPLACEMENTS)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    doc.save(args.output)

    result = {
        "schema_version": 1,
        "book_id": "book-01",
        "action": "apply_ensemble_revision",
        "source": {"path": str(args.source), "sha256": actual},
        "output": {"path": str(args.output), "sha256": sha256(args.output)},
        "issue_ids": ["ENS-001"],
        "chapters": [22, 23, 25, 26, 27],
        "changed_source_paragraphs": len(changes),
        "resulting_paragraph_delta": sum(len(item["after"]) - 1 for item in changes),
        "changes": changes,
    }
    args.log.parent.mkdir(parents=True, exist_ok=True)
    args.log.write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(result["output"], ensure_ascii=False))


if __name__ == "__main__":
    main()
