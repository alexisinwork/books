def replace(chapter, issue, start, after, reason, end=None):
    global text
    begin = text.index(start)
    stop = text.index(end, begin) if end else text.index('\n\n', begin)
    before = text[begin:stop]
    actual_chapter = int(text[:begin].rsplit('## Глава ', 1)[1].split('.', 1)[0])
    assert actual_chapter == chapter
    text = text[:begin] + after + text[stop:]
    changes.append(dict(id=f'{issue}-{len(changes)+1:02d}', issue=issue, chapter=chapter,
                        before=before, after=after, reason=reason))


