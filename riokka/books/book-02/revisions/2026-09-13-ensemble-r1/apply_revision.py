def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--log", type=Path, required=True)
    args = parser.parse_args()

    actual = sha256(args.source)
    if actual != SOURCE_SHA256:
        raise ValueError(f"source hash mismatch: expected {SOURCE_SHA256}, got {actual}")

    text = args.source.read_text(encoding="utf-8")
    applied = []
    for item in CHANGES:
        count = text.count(item["before"])
        if count != 1:
            raise ValueError(f"{item['id']}: expected one exact match, found {count}")
        text = text.replace(item["before"], item["after"], 1)
        applied.append(item)

    # Remove only separators used as accidental chapter boundaries. Keep the
    # intentional divider inside chapter 18.
    boundary = re.compile(r"\n-----\n\n(?=## Глава )")
    separator_count = len(boundary.findall(text))
    if separator_count != 6:
        raise ValueError(f"expected six interchapter separators, found {separator_count}")
    text = boundary.sub("\n", text)
    applied.append(
        change(
            "B02-ENS-030",
            0,
            ["ENS-006"],
            "Удалить шесть случайных межглавных разделителей; внутриглавную отбивку главы 18 сохранить.",
            "----- перед главами 2, 4, 5, 6, 7 и 9",
            "граница главы определяется заголовком; служебная строка удалена",
        )
    )

    if not text.endswith("\n"):
        text += "\n"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    result = {
        "schema_version": 1,
        "book_id": "book-02",
        "action": "apply_ensemble_revision",
        "source": {"path": str(args.source), "sha256": actual},
        "output": {"path": str(args.output), "sha256": sha256(args.output)},
        "issue_ids": [f"ENS-{n:03d}" for n in range(1, 8)],
        "rejected_issue_ids": ["ENS-008"],
        "changed_chapters": sorted({x["chapter"] for x in applied if x["chapter"]}),
        "changes": applied,
    }
    args.log.parent.mkdir(parents=True, exist_ok=True)
    args.log.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result["output"], ensure_ascii=False))


if __name__ == "__main__":
    main()
