def main() -> int:
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    text = src.read_text(encoding="utf-8")
    got = hashlib.sha256(text.encode("utf-8")).hexdigest()
    if got != SRC_SHA:
        print(f"ВХІДНИЙ ФАЙЛ НЕ ТОЙ: {got}", file=sys.stderr)
        return 2
    log, failed = [], []
    for o in OPS:
        n = text.count(o["old"])
        if n != 1:
            failed.append((o["id"], n))
            continue
        text = text.replace(o["old"], o["new"], 1)
        log.append(o)
    if failed:
        for oid, n in failed:
            print(f"НЕ ЗАСТОСОВАНО {oid}: знайдено {n} входжень", file=sys.stderr)
        return 1
    dst.write_text(text, encoding="utf-8")
    out_sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
    Path(str(dst) + ".log.json").write_text(
        json.dumps({"source_sha256": SRC_SHA, "result_sha256": out_sha,
                    "operations": log}, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"операцій застосовано: {len(log)}")
    print(f"SHA-256 результату: {out_sha}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
